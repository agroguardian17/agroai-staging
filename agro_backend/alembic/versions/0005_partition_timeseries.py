UPGRADE_SQL = rf"""
DROP TABLE IF EXISTS node_sensor_readings CASCADE;
DROP TABLE IF EXISTS weather_station_readings CASCADE;
DROP TABLE IF EXISTS weather_forecasts CASCADE;

-- node_sensor_readings: partitioned by recorded_at -------------------------
CREATE TABLE node_sensor_readings (
{_NODE_COLUMNS},
    PRIMARY KEY (reading_id, recorded_at),
    CONSTRAINT node_sensor_readings_idem UNIQUE (node_id, recorded_at)
) PARTITION BY RANGE (recorded_at);
CREATE INDEX node_sensor_readings_plot_time   ON node_sensor_readings (plot_id, recorded_at DESC);
CREATE INDEX node_sensor_readings_farm_time   ON node_sensor_readings (farm_id, recorded_at DESC);
CREATE INDEX node_sensor_readings_tenant_time ON node_sensor_readings (tenant_id, recorded_at DESC);

-- weather_station_readings: partitioned by recorded_at ---------------------
CREATE TABLE weather_station_readings (
{_WEATHER_COLUMNS},
    PRIMARY KEY (weather_id, recorded_at),
    CONSTRAINT weather_station_readings_idem UNIQUE (master_node_id, recorded_at)
) PARTITION BY RANGE (recorded_at);
CREATE INDEX weather_station_readings_farm_time   ON weather_station_readings (farm_id, recorded_at DESC);
CREATE INDEX weather_station_readings_tenant_time ON weather_station_readings (tenant_id, recorded_at DESC);

-- weather_forecasts: partitioned by fetched_at -----------------------------
CREATE TABLE weather_forecasts (
{_FORECAST_COLUMNS},
    PRIMARY KEY (forecast_id, fetched_at)
) PARTITION BY RANGE (fetched_at);
CREATE INDEX weather_forecasts_lookup ON weather_forecasts (farm_id, forecast_for_date, forecast_hour);
CREATE INDEX weather_forecasts_tenant_time ON weather_forecasts (tenant_id, fetched_at DESC);

-- 13 monthly child partitions (current month + 12 forward) -----------------
DO $$
DECLARE
    i           INT;
    start_date  DATE;
    end_date    DATE;
    base_date   DATE := date_trunc('month', now())::date;
    suffix      TEXT;
BEGIN
    FOR i IN 0..12 LOOP
        start_date := (base_date + (i      || ' month')::interval)::date;
        end_date   := (base_date + ((i + 1) || ' month')::interval)::date;
        suffix     := to_char(start_date, 'YYYYMM');

        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS node_sensor_readings_p%s '
            'PARTITION OF node_sensor_readings FOR VALUES FROM (%L) TO (%L);',
            suffix, start_date, end_date);

        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS weather_station_readings_p%s '
            'PARTITION OF weather_station_readings FOR VALUES FROM (%L) TO (%L);',
            suffix, start_date, end_date);

        EXECUTE format(
            'CREATE TABLE IF NOT EXISTS weather_forecasts_p%s '
            'PARTITION OF weather_forecasts FOR VALUES FROM (%L) TO (%L);',
            suffix, start_date, end_date);
    END LOOP;
END
$$;
"""


# Downgrade re-creates the plain (non-partitioned) tables so 0001/0004 can drop
# them cleanly. Includes the v3 columns (harmless superset).
DOWNGRADE_SQL = rf"""
DROP TABLE IF EXISTS node_sensor_readings CASCADE;
DROP TABLE IF EXISTS weather_station_readings CASCADE;
DROP TABLE IF EXISTS weather_forecasts CASCADE;

CREATE TABLE node_sensor_readings (
{_NODE_COLUMNS},
    PRIMARY KEY (reading_id),
    CONSTRAINT node_sensor_readings_idem UNIQUE (node_id, recorded_at)
);
CREATE TABLE weather_station_readings (
{_WEATHER_COLUMNS},
    PRIMARY KEY (weather_id),
    CONSTRAINT weather_station_readings_idem UNIQUE (master_node_id, recorded_at)
);
CREATE TABLE weather_forecasts (
{_FORECAST_COLUMNS},
    PRIMARY KEY (forecast_id)
);
"""


def upgrade() -> None:
    op.execute(UPGRADE_SQL)


def downgrade() -> None:
    op.execute(DOWNGRADE_SQL)
