"""0005 convert time-series tables to monthly range partitions.

``node_sensor_readings`` and ``weather_station_readings`` are partitioned by
``recorded_at``; ``weather_forecasts`` by ``fetched_at`` (it has no
``recorded_at`` -- see docs/SCHEMA_DECISIONS.md). The three plain tables created
in 0001 are dropped and re-created as partitioned parents with the full column
set, including the Part 2.4 v3 additions for ``node_sensor_readings``. 13
monthly child partitions (current month + 12 forward) are created per table.

This migration assumes the three tables are empty (initial setup). Nothing has
inbound FKs to them, so DROP/CREATE is safe.

Revision ID: 0005
Revises: 0004
Create Date: Phase 1
"""

